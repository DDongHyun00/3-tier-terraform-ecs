-- 게시판 초기 스키마 (엔티티 7개)
-- 모든 시간 컬럼은 애플리케이션(JPA Auditing)이 채운다.

CREATE TABLE users (
    user_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(15)  NOT NULL,
    password    VARCHAR(255) NOT NULL,
    nickname    VARCHAR(10)  NOT NULL,
    role        VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_nickname UNIQUE (nickname)
);

CREATE TABLE posts (
    post_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    title       VARCHAR(255) NOT NULL,
    content     TEXT         NOT NULL,
    view_count  INTEGER      NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    CONSTRAINT fk_posts_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);
CREATE INDEX idx_posts_user_id ON posts (user_id);
CREATE INDEX idx_posts_created_at ON posts (created_at);

CREATE TABLE comments (
    comment_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT NOT NULL,
    user_id     BIGINT NOT NULL,
    parent_id   BIGINT,
    content     TEXT   NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    CONSTRAINT fk_comments_post   FOREIGN KEY (post_id)   REFERENCES posts (post_id),
    CONSTRAINT fk_comments_user   FOREIGN KEY (user_id)   REFERENCES users (user_id),
    CONSTRAINT fk_comments_parent FOREIGN KEY (parent_id) REFERENCES comments (comment_id)
);
CREATE INDEX idx_comments_post_id   ON comments (post_id);
CREATE INDEX idx_comments_user_id   ON comments (user_id);
CREATE INDEX idx_comments_parent_id ON comments (parent_id);

CREATE TABLE post_likes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    post_id     BIGINT NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    CONSTRAINT uk_post_likes_user_post UNIQUE (user_id, post_id),
    CONSTRAINT fk_post_likes_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_post_likes_post FOREIGN KEY (post_id) REFERENCES posts (post_id)
);
CREATE INDEX idx_post_likes_post_id ON post_likes (post_id);

CREATE TABLE comment_likes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    comment_id  BIGINT NOT NULL,
    CONSTRAINT uk_comment_likes_user_comment UNIQUE (user_id, comment_id),
    CONSTRAINT fk_comment_likes_user    FOREIGN KEY (user_id)    REFERENCES users (user_id),
    CONSTRAINT fk_comment_likes_comment FOREIGN KEY (comment_id) REFERENCES comments (comment_id)
);
CREATE INDEX idx_comment_likes_comment_id ON comment_likes (comment_id);

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT  NOT NULL,
    post_id     BIGINT  NOT NULL,
    message     VARCHAR(255),
    read        BOOLEAN NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_notifications_post FOREIGN KEY (post_id) REFERENCES posts (post_id) ON DELETE CASCADE
);
CREATE INDEX idx_notifications_user_id ON notifications (user_id);
CREATE INDEX idx_notifications_post_id ON notifications (post_id);

CREATE TABLE files (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id        BIGINT NOT NULL,
    original_name  VARCHAR(255),
    saved_name     VARCHAR(255),
    CONSTRAINT fk_files_post FOREIGN KEY (post_id) REFERENCES posts (post_id)
);
CREATE INDEX idx_files_post_id ON files (post_id);
